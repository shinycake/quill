#!/usr/bin/env bash
# Copy the parts of Telegram's message-widget runtime that Quill builds into
# third_party/widgets/ and record the upstream commits in
# third_party/widgets/VERSION. build.rs compiles them with `cc` (ui feature).
#
#   widget-sandbox  BSD-3-Clause  the QuickJS sandbox, the trusted validator and
#                                 WidgetHost (packages/desktop/sandbox), the JS
#                                 bundles with their bytecode (WidgetJS)
#   quickjs         MIT           TelegramMessenger/quickjs (quickjs-ng fork), the
#                                 submodule widget-sandbox pins
#   twidget         BSD-3-Clause  TwidgetCore and its litehtml fork (with gumbo)
#
# Only portable sources are copied: Quill paints with its own Rust backend
# (src/ui/widget_runtime/), so no platform backend from twidget/platforms.
# Background: docs/decisions/message-widgets.md.
#
# Usage: scripts/vendor-widgets.sh <widget-sandbox-tag> <twidget-commit>
#   Downloads both trees and the QuickJS commit the tag pins from GitHub
#   (codeload tarballs, no git needed). WIDGETS_SRC=<dir> reuses a download dir.
# Bumping = rerun with the new tag/commit, then follow docs/dependency-updates.md.
set -euo pipefail

TAG="${1:?usage: scripts/vendor-widgets.sh <widget-sandbox-tag> <twidget-commit>}"
TWIDGET="${2:?usage: scripts/vendor-widgets.sh <widget-sandbox-tag> <twidget-commit>}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/third_party/widgets"
API=https://api.github.com/repos/TelegramMessenger
CODELOAD=https://codeload.github.com/TelegramMessenger

WORK="${WIDGETS_SRC:-}"
if [[ -z "$WORK" ]]; then
  WORK="$(mktemp -d)"
  trap 'rm -rf "$WORK"' EXIT
fi
mkdir -p "$WORK"

json_field() { python3 -I -c "import json,sys; d=json.load(sys.stdin); print($1)"; }

SANDBOX_COMMIT="$(curl -fsSL "$API/widget-sandbox/commits/$TAG" | json_field 'd["sha"]')"
TWIDGET_COMMIT="$(curl -fsSL "$API/twidget/commits/$TWIDGET" | json_field 'd["sha"]')"
QJS_COMMIT="$(curl -fsSL "$API/widget-sandbox/contents/packages/ios/Sources/CQuickJS?ref=$SANDBOX_COMMIT" |
  json_field '[e["sha"] for e in d if e["name"] == "quickjs"][0]')"

fetch() { # fetch <repo> <commit>: unpacks into $WORK/<repo>
  local repo="$1" commit="$2"
  if [[ ! -d "$WORK/$repo" ]]; then
    curl -fsSL -o "$WORK/$repo.tar.gz" "$CODELOAD/$repo/tar.gz/$commit"
    mkdir -p "$WORK/$repo.tmp"
    tar -xzf "$WORK/$repo.tar.gz" -C "$WORK/$repo.tmp"
    mv "$WORK/$repo.tmp/"* "$WORK/$repo"
    rm -rf "$WORK/$repo.tmp" "$WORK/$repo.tar.gz"
  fi
}
fetch widget-sandbox "$SANDBOX_COMMIT"
fetch twidget "$TWIDGET_COMMIT"
fetch quickjs "$QJS_COMMIT"

KEEP="$(cat "$DEST/QUILL-CHANGES.md" 2>/dev/null || true)"
rm -rf "$DEST"
mkdir -p "$DEST"
[[ -z "$KEEP" ]] || printf '%s\n' "$KEEP" >"$DEST/QUILL-CHANGES.md"

# copy <repo> <dest-subdir> <dir> <find args...>: matching files, same layout.
copy() {
  local repo="$1" sub="$2" dir="$3"
  shift 3
  (cd "$WORK/$repo" && find "$dir" -type f "$@" -print0) |
    while IFS= read -r -d '' file; do
      mkdir -p "$DEST/$sub/$(dirname "$file")"
      cp "$WORK/$repo/$file" "$DEST/$sub/$file"
    done
}

S=widget-sandbox
copy $S sandbox . -maxdepth 1 \( -name LICENSE -o -name THIRD_PARTY_NOTICES.md -o -name VERSION.json \)
copy $S sandbox packages/desktop/sandbox/include -name '*.h'
copy $S sandbox packages/desktop/sandbox/src -name '*.cpp'
copy $S sandbox packages/desktop/WidgetJS \( -name '*.js' -o -name '*.qbc' \)
copy $S sandbox packages/ios/Sources/CQuickJS/include -name qjs_shim.h
copy $S sandbox packages/ios/Sources/CQuickJS/shim -name '*.c'
# Smoke-test widgets for the native test (src/ui/widget_runtime/native_tests.rs)
# and the demo fixtures.
copy $S sandbox corpus/compat -name '*.html'

copy quickjs quickjs . -maxdepth 1 \( -name LICENSE -o -name '*.h' -o -name quickjs.c -o -name dtoa.c \
  -o -name libregexp.c -o -name libunicode.c \) ! -name 'quickjs-libc.h' ! -name 'unicode_gen_def.h'

copy twidget twidget . -maxdepth 1 \( -name LICENSE -o -name THIRD_PARTY_NOTICES.md \)
copy twidget twidget core/include -name '*.h'
copy twidget twidget core/src \( -name '*.cpp' -o -name '*.h' \)
copy twidget twidget litehtml ! -path '*/visualc/*'
copy twidget twidget litehtml/src/gumbo/visualc -name '*.h'

# The profile's UA layer, as twidget's CMakeLists.txt generates it at configure time.
mkdir -p "$DEST/twidget/generated"
python3 -I - "$WORK/$S/packages/core/profile.json" "$DEST/twidget/generated/tw_ua_stylesheet.h" <<'PY'
import json, sys
css = json.load(open(sys.argv[1]))["tables"]["uaStylesheet"]
assert ")tw-ua\"" not in css
with open(sys.argv[2], "w") as out:
    out.write("// Generated by scripts/vendor-widgets.sh from widget-sandbox's packages/core/profile.json (tables.uaStylesheet).\n")
    out.write("#pragma once\n")
    out.write('inline constexpr const char* TW_UA_STYLESHEET = R"tw-ua(' + css + ')tw-ua";\n')
PY

patch --quiet --fuzz=0 --no-backup-if-mismatch -p1 -d "$DEST" <"$ROOT/native/patches/twidget-quill.patch"

VERSION="$(python3 -I -c "import json; print(json.load(open('$WORK/$S/VERSION.json'))['version'])")"
printf 'widget-sandbox %s %s\nversion %s\nquickjs %s\ntwidget %s\n' \
  "$TAG" "$SANDBOX_COMMIT" "$VERSION" "$QJS_COMMIT" "$TWIDGET_COMMIT" >"$DEST/VERSION"
echo "Vendored widget-sandbox $TAG ($SANDBOX_COMMIT), quickjs $QJS_COMMIT, twidget $TWIDGET_COMMIT:" \
  "$(find "$DEST" -type f | wc -l | tr -d ' ') files"
